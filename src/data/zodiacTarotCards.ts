/**
 * Get the active deck of Tarot Archetypes for the selected Zodiac sign.
 * Returns exactly 12 cards for EVERY Zodiac sign (and universal deck for Cosmos).
 */
export function getZodiacArchetypes(
  zodiac: ZodiacSign,
  universalDeck: TarotArchetype[]
): TarotArchetype[] {
  if (zodiac.id === 'all' || !ZODIAC_TAROT_DECKS[zodiac.id]) {
    return universalDeck;
  }

  const rawDeck = ZODIAC_TAROT_DECKS[zodiac.id];
  const style = ELEMENT_CARD_STYLES[zodiac.element] || ELEMENT_CARD_STYLES['Vũ Trụ'];

  return rawDeck.map((item) => ({
    ...item,
    ...style,
  }));
}
